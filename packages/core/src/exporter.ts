const PRIORITY: Record<string, Record<Lang, string>> = {
  must: { en: "must", ko: "필수" },
  should: { en: "should", ko: "권장" },
  could: { en: "could", ko: "선택" },
  wont: { en: "won't", ko: "제외" },
};

const STATUS_LABEL: Record<Status, Record<Lang, string>> = {
  planned: { en: "planned", ko: "미진행" },
  in_progress: { en: "in progress", ko: "진행 중" },
  blocked: { en: "blocked", ko: "막힘" },
  done: { en: "done", ko: "완료" },
};

class Ctx {
  readonly lang: Lang;
  readonly s: (typeof STR)[Lang];
  readonly rollup: Record<string, Status>;
  readonly byId: Map<string, Node>;
  readonly answers: Map<string, Answer>;

  constructor(readonly spec: ProjectSpec) {
    this.lang = spec.project.outputLanguage;
    this.s = STR[this.lang];
    this.rollup = computeRollup(spec);
    this.byId = new Map(spec.nodes.map((n) => [n.id, n] as const));
    this.answers = new Map(spec.answers.map((a) => [a.questionId, a] as const));
  }

  status(id: string): string {
    const st = this.rollup[id] ?? "planned";
    return STATUS_LABEL[st][this.lang];
  }

  title(id: string): string {
    return this.byId.get(id)?.title ?? id;
  }

  ofType<T extends Node["type"]>(type: T): Extract<Node, { type: T }>[] {
    return this.spec.nodes.filter((n): n is Extract<Node, { type: T }> => n.type === type);
  }

  children(id: string, type?: Node["type"]): Node[] {
    return this.spec.edges
      .filter((e) => e.kind === "contains" && e.from === id)
      .map((e) => this.byId.get(e.to))
      .filter((n): n is Node => !!n && (!type || n.type === type));
  }

  edgesFrom(id: string, kind: Edge["kind"]): Edge[] {
    return this.spec.edges.filter((e) => e.from === id && e.kind === kind);
  }

  /** Marker appended to anything an agent decided. */
  mark(p: Provenance | undefined): string {
    if (!p || p.source !== "ai") return "";
    const why = p.rationale ? `: ${p.rationale}` : "";
    return ` _(${p.reviewed ? this.s.ai : this.s.aiUnreviewed}${why})_`;
  }

  /** Answer as lines of text, using the translation when the output language is English. */
  answerLines(id: string): { lines: string[]; mark: string } | undefined {
    const a = this.answers.get(id);
    if (!a || a.value === undefined) return undefined;
    const v = this.lang === "en" ? (a.valueEn ?? a.value) : a.value;
    const lines = Array.isArray(v) ? v : typeof v === "boolean" ? [v ? this.s.yes : this.s.no] : [v];
    return { lines, mark: this.mark(a.provenance) };
  }
}

const bullets = (items: string[], suffix = "") => items.map((i) => `- ${i}${suffix}`).join("\n");

function uniq(items: string[]): string[] {
  return [...new Set(items.map((i) => i.trim()).filter(Boolean))];
}

/** Items from a node field merged with an answer, with the AI mark on answer items. */
function mergedList(c: Ctx, base: string[], answerId: string): string {
  const a = c.answerLines(answerId);
  const baseSet = new Set(base.map((b) => b.trim()));
  const lines = [
    ...base.map((b) => `- ${b}`),
    ...(a ? uniq(a.lines).filter((l) => !baseSet.has(l)).map((l) => `- ${l}${a.mark}`) : []),
  ];
  return lines.length ? lines.join("\n") : c.s.none;
}

function header(c: Ctx, title: string, withLegend = true): string {
  const legend = withLegend ? `\n> ${c.s.aiLegend}\n` : "";
  return `# ${c.spec.project.name} — ${title}\n\n<!-- ${c.s.generated} -->${legend}\n`;
}

function renderPrd(c: Ctx): string {
  const { s, spec } = c;
  const vision = c.ofType("vision")[0];
  const out: string[] = [header(c, s.prd)];

  const problemAnswer = c.answerLines("problem-statement");
  out.push(`## ${s.problem}\n`);
  const problem = vision?.problem ?? problemAnswer?.lines.join(" ");
  out.push(problem ? problem + (vision?.problem ? "" : problemAnswer!.mark) : s.none, "");

  out.push(`## ${s.goals}\n`, mergedList(c, vision?.goals ?? [], "problem-goals"), "");
  out.push(`## ${s.nonGoals}\n`, mergedList(c, vision?.nonGoals ?? [], "scope-nongoals"), "");

  out.push(`## ${s.users}\n`);
  const personas = c.ofType("persona");
  if (personas.length) {
    for (const p of personas) {
      out.push(`### ${p.title}${c.mark(p.provenance)}`);
      if (p.summary) out.push(c.lang === "en" ? (p.summaryEn ?? p.summary) : p.summary);
      if (p.jobsToBeDone.length) out.push(bullets(p.jobsToBeDone));
      out.push("");
    }
  } else {
    out.push(mergedList(c, [], "users-who"), "");
  }

  out.push(`## ${s.features}\n`);
  const features = c.ofType("feature");
  if (features.length) {
    out.push(`| ${s.featureCols.join(" | ")} |`, `| ${s.featureCols.map(() => "---").join(" | ")} |`);
    for (const f of features) {
      out.push(
        `| ${f.title}${c.mark(f.provenance)} | ${PRIORITY[f.priority]![c.lang]} | ${f.inMvp ? s.yes : s.no} | ${c.status(f.id)} |`,
      );
    }
  } else {
    out.push(mergedList(c, [], "scope-mvp"));
  }
  out.push("");

  const stories = c.ofType("story");
  if (stories.length) {
    out.push(`## ${s.stories}\n`);
    for (const st of stories) {
      out.push(`### ${st.title}${c.mark(st.provenance)}`);
      if (st.asA || st.iWant || st.soThat) {
        out.push(`As a ${st.asA ?? "…"}, I want ${st.iWant ?? "…"}, so that ${st.soThat ?? "…"}.`);
      }
      if (st.acceptance.length) {
        out.push("", `**${s.acceptance}**`);
        for (const a of st.acceptance) out.push(`- Given ${a.given}, when ${a.when}, then ${a.then}`);
      }
      out.push("");
    }
  }

  const risks = c.ofType("risk");
  out.push(`## ${s.risks}\n`);
  if (risks.length) {
    for (const r of risks) {
      out.push(`- **${r.title}** (${r.likelihood}/${r.impact})${c.mark(r.provenance)}`);
      if (r.mitigation) out.push(`  - ${s.mitigation}: ${r.mitigation}`);
    }
  }
  const assumptions = c.answerLines("risks-assumptions");
  if (assumptions) out.push(...assumptions.lines.map((l) => `- ${l}${assumptions.mark}`));
  if (!risks.length && !assumptions) out.push(s.none);
  out.push("");

  const comp = computeCompleteness(QUESTION_BANK, spec);
  out.push(`## ${s.open}\n`, `**${s.openP0}**`);
  out.push(comp.missingP0.length ? bullets(comp.missingP0.map((id) => `\`${id}\``)) : s.none, "");
  const queue = reviewQueue(spec);
  out.push(`**${s.review}**`);
  out.push(queue.length ? bullets(queue.map((a) => `\`${a.questionId}\``)) : s.none, "");

  return out.join("\n");
}

function renderScreens(c: Ctx): string {
  const { s } = c;
  const out: string[] = [header(c, s.screens)];
  const screens = c.ofType("screen");
  if (!screens.length) {
    out.push(c.answerLines("ia-screens")?.lines.map((l) => `- ${l}`).join("\n") ?? s.none);
  }

  for (const sc of screens) {
    out.push(`## ${sc.title}${sc.route ? ` (\`${sc.route}\`)` : ""}${c.mark(sc.provenance)}`);
    out.push(`Status: ${c.status(sc.id)}`, "");
    if (sc.summary) out.push(c.lang === "en" ? (sc.summaryEn ?? sc.summary) : sc.summary, "");
    if (sc.wireframe) out.push(`Wireframe: \`${sc.wireframe}\``, "");

    if (sc.states.length) {
      out.push(`**${s.states}**`);
      out.push(bullets(sc.states.map((st) => (st.description ? `${st.name}: ${st.description}` : st.name))), "");
    }

    const ints = c.children(sc.id, "interaction");
    if (ints.length) {
      out.push(`**${s.interactions}**`);
      for (const i of ints) {
        if (i.type === "interaction") out.push(`- ${i.trigger} → ${i.result}${c.mark(i.provenance)}`);
      }
      out.push("");
    }

    const nav = c.edgesFrom(sc.id, "navigates");
    if (nav.length) {
      out.push(`**${s.navigation}**`);
      out.push(bullets(nav.map((e) => `${e.label ? `${e.label} → ` : "→ "}${c.title(e.to)}`)), "");
    }

    const data = c.edgesFrom(sc.id, "uses_data");
    if (data.length) {
      out.push(`**${s.data}**`, bullets(data.map((e) => c.title(e.to))), "");
    }
  }

  const required = c.answerLines("interactions-states");
  if (required) {
    out.push(`## ${s.states}\n`, `${required.lines.join(", ")}${required.mark}`, "");
  }
  return out.join("\n");
}

const mermaidId = (id: string) => `n_${id.replace(/[^A-Za-z0-9]/g, "_")}`;
const mermaidText = (t: string) => t.replace(/"/g, "'");

function renderFlows(c: Ctx): string {
  const { s } = c;
  const out: string[] = [header(c, s.flows, false)];
  const nav = c.spec.edges.filter((e) => e.kind === "navigates");

  if (nav.length) {
    const used = new Set(nav.flatMap((e) => [e.from, e.to]));
    out.push("```mermaid", "flowchart LR");
    for (const id of used) out.push(`  ${mermaidId(id)}["${mermaidText(c.title(id))}"]`);
    for (const e of nav) {
      const label = e.label ? `|"${mermaidText(e.label)}"|` : "";
      out.push(`  ${mermaidId(e.from)} -->${label} ${mermaidId(e.to)}`);
    }
    out.push("```", "");
  } else {
    out.push(s.noFlows, "");
  }

  for (const f of c.ofType("flow")) {
    out.push(`## ${f.title}`);
    if (f.summary) out.push(f.summary);
    if (f.mermaid) out.push("```mermaid", f.mermaid.trim(), "```");
    out.push("");
  }

  const main = c.answerLines("flows-main");
  if (main) out.push(`## ${s.mainFlow}\n`, main.lines.join("\n") + main.mark, "");
  return out.join("\n");
}

function renderTasks(c: Ctx): string {
  const { s } = c;
  const out: string[] = [header(c, s.tasks), s.taskHow, ""];
  const tasks = [...c.ofType("task")].sort(
    (a, b) => (a.order ?? Number.MAX_SAFE_INTEGER) - (b.order ?? Number.MAX_SAFE_INTEGER),
  );

  if (!tasks.length) {
    out.push(c.answerLines("tasks-order")?.lines.map((l) => `- [ ] ${l}`).join("\n") ?? s.none);
  }

  for (const t of tasks) {
    const st = c.status(t.id);
    const box = c.rollup[t.id] === "done" ? "x" : " ";
    out.push(`- [${box}] **${t.title}** (\`${t.id}\`) — ${st}${c.mark(t.provenance)}`);
    if (t.summary) out.push(`  - ${t.summary}`);
    const impl = c.edgesFrom(t.id, "implements").map((e) => c.title(e.to));
    if (impl.length) out.push(`  - ${s.implements}: ${impl.join(", ")}`);
    const deps = c.edgesFrom(t.id, "depends_on").map((e) => c.title(e.to));
    if (deps.length) out.push(`  - ${s.dependsOn}: ${deps.join(", ")}`);
    if (t.doneWhen.length) out.push(`  - ${s.doneWhen}:`, ...t.doneWhen.map((d) => `    - ${d}`));
  }
  out.push("");
  return out.join("\n");
}

function renderAgents(c: Ctx): string {
  const { s, spec } = c;
  const out: string[] = [header(c, "AGENTS.md")];

  out.push(`## ${s.project}\n`);
  out.push(spec.project.description ?? c.ofType("vision")[0]?.problem ?? "", "");

  out.push(`## ${s.readFirst}\n`, "- PRD.md", "- SCREENS.md", "- FLOWS.md", "- TASKS.md", "");

  out.push(`## ${s.stack}\n`);
  const decisions = c.ofType("decision");
  const stack: string[] = decisions.map(
    (d) => `**${d.title}**: ${d.choice ?? "?"}${d.rationale ? ` — ${d.rationale}` : ""}${c.mark(d.provenance)}`,
  );
  for (const id of ["stack-platform", "stack-language", "data-storage"]) {
    const a = c.answerLines(id);
    if (a) stack.push(`${id}: ${a.lines.join(", ")}${a.mark}`);
  }
  out.push(stack.length ? bullets(stack) : s.none, "");

  out.push(`## ${s.conventions}\n`);
  const conv: string[] = [];
  for (const id of ["stack-conventions", "stack-constraints", "stack-testing"]) {
    const a = c.answerLines(id);
    if (a) conv.push(...a.lines.map((l) => `${l}${a.mark}`));
  }
  out.push(conv.length ? bullets(conv) : s.none, "");

  out.push(`## ${s.scopeRules}\n`, `**${s.doNotBuild}**`);
  out.push(mergedList(c, c.ofType("vision")[0]?.nonGoals ?? [], "scope-nongoals"), "");

  out.push(`## ${s.workflow}\n`, s.workflowItems.map((w, i) => `${i + 1}. ${w}`).join("\n"), "");

  const missing = untranslated(spec).length;
  if (c.lang === "en" && missing > 0) out.push(`> ${s.untranslated(missing)}`, "");
  return out.join("\n");
}

/** Render every md deliverable. Keys are file names. */
export function exportMarkdown(spec: ProjectSpec): Record<string, string> {
  const c = new Ctx(spec);
  return {
    "AGENTS.md": renderAgents(c),
    "PRD.md": renderPrd(c),
    "SCREENS.md": renderScreens(c),
    "FLOWS.md": renderFlows(c),
    "TASKS.md": renderTasks(c),
  };
}
